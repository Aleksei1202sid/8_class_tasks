# Напишите программу, которая запрашивает у пользователя 2 числа и
# выводит наибольшее из них.

первое_число = float(input('Введите первое число: '))
второе_число = float(input('Введите второе число: '))
if первое_число > второе_число:
    print(первое_число)
elif первое_число < второе_число:
    print(второе_число)
else:
    print('Одинаковые числа, попробуй заново!')
