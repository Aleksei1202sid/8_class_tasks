# Создайте программу, которая запрашивает у пользователя два числа и выводит
# результат умножения и деления(если деление возможно).
import sys

первое_число = int(input('Введите первое число: '))
второе_число = int(input('Введите второе число: '))

if второе_число == 0:
    print('На "0" делить нельзя!')
    sys.exit()

произведение = первое_число * второе_число
частное = первое_число / второе_число

print(f'Произведение чисел - {произведение}, частное чисел - {частное} ')
