# Создайте программу, которая принимает от пользователя три
# стороны треугольника и проверяет, существует ли такой
# треугольник. Если существует, определите его тип
# (равносторонний, равнобедренны или разносторонний)
a = int(input('Введите первую сторону: '))
b = int(input('Введите вторую сторону: '))
c = int(input('Введите третью сторону: '))

if a + b > c and a + c > b and b + c > a:
    if a > 0 and b > 0 and c > 0:
        print('Такой треугольник существует')

if a == b and b == c and a == c:
    print('Треугольник равносторонний')
elif a == b or a == c or b == c:
    print('Треугольник равнобедренный')
else:
    print('Треугорьник разносторонний')
