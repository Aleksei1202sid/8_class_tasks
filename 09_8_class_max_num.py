# Напишите программу, которая запрашивает у пользователя три числа и
# выводит наибольшее из них.

первое_число = float(input('Введите первое число: '))
второе_число = float(input('Введите второе число: '))
третье_число = float(input('Введите третье число: '))

макс_число = max(первое_число, второе_число, третье_число)

print(макс_число)
