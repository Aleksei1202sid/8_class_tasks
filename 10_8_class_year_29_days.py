# 4 Создайте программу, которая запрашивает у пользователя год и определяет,
# является ли он високосным.

год_рождения = int(input('Введите год своего рождения: '))

if (
    год_рождения % 4 == 0 and
    год_рождения % 100 == 0 and
    год_рождения % 400 == 0
):
    год = 'високосным'
elif год_рождения % 4 == 0 and год_рождения % 100 == 0:
    год = 'невисокосным'
elif год_рождения % 4 == 0:
    год = 'високосным'
else:
    год = 'невисокосным'

print(f'Ваш год рождения {год_рождения} является {год}')
