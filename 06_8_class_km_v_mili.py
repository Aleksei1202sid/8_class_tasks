# Создайте программу, которая запрашивает у пользователя
# расстояние в километрах и переводит его в мили
# (1 км = 0,621371 мили)
километры = int(input('Введите рассояние в километрах: '))
мили = 0.621371

расстояние_в_милях = километры * мили

print(f'Расстояние в милях - {расстояние_в_милях:.6f}')
