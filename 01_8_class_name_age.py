# Напишите программу, которая запрашивает у пользователя его имя и возраст,
# а затем выводит сообщение: "Привет, [имя]! Тебе уже [возраст] лет."
import sys

имя = input('Введите имя: ')
возраст = int(input('Введите возраст: '))

if возраст < 10:
    print('Ты еще ребенок! Возраст может быть только старше 10 лет')
    sys.exit()
elif возраст > 99:
    print('Странно, но перестань обманывать! Возраст должен быть до 99 лет')
    sys.exit()

# Определяем правильное склонение слова "год"
if 10 <= возраст <= 20:
    годы = 'лет'
elif возраст % 10 == 1:
    годы = 'год'
elif возраст % 10 in (2, 3, 4):
    годы = 'года'
else:
    годы = 'лет'


print(f'Привет, {имя}! Тебе уже {возраст} {годы}.')
