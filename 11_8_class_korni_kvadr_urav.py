# Напишите программу, которая запрашивает у пользователя коэфиценты квадратного
# уравнения и вычесляет его корни, если они существуют.
import math

print('Для решения квадратного уравнения ax^2 + bx + c = 0')
print('Введите коэффициенты:')

a = int(input('Введите коэффициент a: '))
b = int(input('Введите коэффициент b: '))
c = int(input('Введите коэффициент c: '))

if a == 0:
    print('Коффициент "a" не может быть навен 0')
else:
    d = b**2 - 4 * a * c

    if d > 0:
        x1 = (-b + math.sqrt(d)) / (2 * a)
        x2 = (-b - math.sqrt(d)) / (2 * a)
        print(f'Дискриминант D = {d:.2f}, два корня:')
        print(f'x1 = {x1:.2f}')
        print(f'x2 = {x2:.2f}')
    elif d == 0:
        x = -b / (2 * a)
        print('Дискриминант D = 0, один корень:')
        print(f'x = {x:.2f}')
    else:
        print(f'Дискриминант D = {d:.2f} < 0 - действительных корней нет')
