# Напишите программу, которая конвертирует температуру из градусов
# Цельсия в градусы Фаренгейта и наоборот. Пользователь должен ввести
# температуру и выбрать направление преобразования.
def фаренгейты_в_цельсий(f):
    return (f - 32) * 5 / 9


def цельсий_в_фаренгейты(c):
    return c * 9 / 5 + 32


print('Выберите направление перевода:')
print('1 — Фаренгейты → Цельсий')
print('2 — Цельсий → Фаренгейты')

choice = input('Ваш выбор (1 или 2): ').strip()

if choice == '1':
    f = float(input('Введите температуру в градусах Фаренгейта: '))
    c = фаренгейты_в_цельсий(f)
    print(f'{f} °F = {c:.2f} °C')
elif choice == '2':
    c = float(input('Введите температуру в градусах Цельсия: '))
    f = цельсий_в_фаренгейты(c)
    print(f'{c} °C = {f:.2f} °F')
else:
    print('Некорректный выбор. Введите 1 или 2.')
