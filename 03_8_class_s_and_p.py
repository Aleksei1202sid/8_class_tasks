# Напишите программу, которая запрашивает у пользователя длину и ширину
# прямоугольника и выводит его площадь и периметр.

длина = int(input('Введите длину: '))
ширина = int(input('Введите ширину: '))
площадь = длина * ширина
периметр = (длина + ширина) * 2

print(f'Площадь прямоугольника - {площадь}, '
      'периметр прямоугольника - {периметр}')
